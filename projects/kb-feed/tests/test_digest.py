def test_process_digest_reply_sends_latest_digest_and_decision_to_agent(tmp_path) -> None:
    store = _store(tmp_path)
    digest_file = tmp_path / "proposals" / "weekly-digest.md"
    digest_file.parent.mkdir()
    digest_file.write_text("Full digest body with proposed item 1", encoding="utf-8")
    store.set_meta("last_weekly_digest_file", str(digest_file))
    store.set_meta(LAST_WEEKLY_DIGEST_TEXT_META_KEY, "Telegram summary")
    captured: dict = {}

    report = process_digest_reply(
        store,
        decision_text="approve item 1 but rename topic to field-tools",
        agent=FakeAgent("Acknowledged\n- approve item 1 with renamed topic", captured=captured),
        proposals_dir=tmp_path / "proposals",
        now=datetime(2026, 6, 1, 11, 0, tzinfo=timezone.utc),
    )

    assert report.ran is True
    assert report.proposals_path is not None
    body = report.proposals_path.read_text(encoding="utf-8")
    assert "approve item 1 but rename topic to field-tools" in body
    assert "Acknowledged" in report.telegram_text
    assert store.get_meta(LAST_WEEKLY_DIGEST_REPLY_TEXT_META_KEY) == report.telegram_text
    prompt = json.loads(captured["prompt"])
    assert prompt["user_decision"] == "approve item 1 but rename topic to field-tools"
    assert "Full digest body" in prompt["latest_digest"]


