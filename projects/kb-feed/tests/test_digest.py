_SAMPLE_DIGEST = """## Summary
Two links need routing; one new topic candidate.

## Proposed moves
- url: https://a.example — topic: obsidian
- url: https://b.example — topic: health

## Possible new topics
- slug: quantum-foo

## Ingest priorities
- url: https://a.example — reason: official docs

## Deferred
- (none)

## Suggested replies
- approve a.example to obsidian
"""


def _store_with_digest(tmp_path):
    store = _StateStore(_Path(tmp_path) / "state.sqlite")
    store.initialize()
    store.set_meta(LAST_WEEKLY_DIGEST_BODY_META_KEY, _SAMPLE_DIGEST)
    return store


def test_parse_digest_sections_splits_by_heading():
    sections = _parse_digest_sections(_SAMPLE_DIGEST)
    assert set(sections) == {"Summary", "Proposed moves", "Possible new topics",
                             "Ingest priorities", "Deferred", "Suggested replies"}
    assert "obsidian" in sections["Proposed moves"]


def test_summary_index_shows_counts_and_commands():
    text = _digest_summary_and_index(_SAMPLE_DIGEST)
    assert "Two links need routing" in text
    assert "Proposed moves: 2" in text
    assert "/kbdigest moves" in text
    assert "/kbdigest priorities" in text


def test_render_digest_section_returns_named_section(tmp_path):
    store = _store_with_digest(tmp_path)
    out = render_digest_section(store, "moves")
    assert out.startswith("## Proposed moves")
    assert "https://a.example" in out


def test_render_digest_section_unknown_arg(tmp_path):
    store = _store_with_digest(tmp_path)
    assert "Unknown digest section" in render_digest_section(store, "nonsense")


def test_render_digest_section_without_digest(tmp_path):
    store = _StateStore(_Path(tmp_path) / "state.sqlite")
    store.initialize()
    assert "No weekly digest" in render_digest_section(store, "moves")
