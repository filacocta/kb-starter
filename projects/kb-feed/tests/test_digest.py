def _build_kb(tmp_path):
    kb_root = tmp_path / "kb"
    (kb_root / "readinglist").mkdir(parents=True)
    (kb_root / "topics" / "obsidian").mkdir(parents=True)
    (kb_root / "topics" / "rockhounding").mkdir(parents=True)
    (kb_root / "readinglist" / "Links.md").write_text(
        "---\nauthor: kb-bot\n---\n# URL Inbox\n\n"
        "- [ ] https://example.com/field-kit — (via Telegram #unfiltered, 2026-06-01)\n",
        encoding="utf-8",
    )
    (kb_root / "readinglist" / "topics.md").write_text(
        "---\nauthor: kb-bot\n---\n# Topic Interests\n\n"
        "- [ ] combine mineral tests with field notebooks\n",
        encoding="utf-8",
    )
    (kb_root / "topics" / "obsidian" / "reading-list.md").write_text(
        "---\nauthor: kb-bot\n---\n# Obsidian Reading List\n\n## Queue\n"
        "- [ ] https://example.com/obsidian-plugin\n",
        encoding="utf-8",
    )
    (kb_root / "topics" / "rockhounding" / "reading-list.md").write_text(
        "---\nauthor: kb-bot\n---\n# Rockhounding Reading List\n\n## Queue\n",
        encoding="utf-8",
    )
    return kb_root


def _store(tmp_path):
    store = StateStore(tmp_path / "state.sqlite")
    store.initialize()
    store.allow_user(111)
    return store


class FakeAgent:
    def __init__(self, response: str, captured: dict | None = None) -> None:
        self._response = response
        self._captured = captured

    def complete(self, prompt: str) -> str:
        if self._captured is not None:
            self._captured["prompt"] = prompt
        return self._response


def _without_chunk_prefixes(chunks: list[str]) -> str:
    return "".join(chunk.split(" ", 1)[1] for chunk in chunks)


def test_split_telegram_message_preserves_long_paragraph_text_with_markers() -> None:
    text = (
        "Weekly KB digest\n\n"
        + "\n\n".join(f"Paragraph {index}: " + ("x" * 700) for index in range(8))
        + "\n\nFull proposal: /tmp/proposals/weekly-digest.md\nCommands: /kbremind 3h, /kbdigest"
    )

    chunks = split_telegram_message(text, limit=1000)

    assert len(chunks) > 1
    assert all(len(chunk) <= 1000 for chunk in chunks)
    assert [chunk.split(" ", 1)[0] for chunk in chunks] == [f"({index}/{len(chunks)})" for index in range(1, len(chunks) + 1)]
    assert _without_chunk_prefixes(chunks) == text
    assert chunks[-1].endswith("Commands: /kbremind 3h, /kbdigest")


def test_split_telegram_message_short_text_has_no_marker() -> None:
    text = "Weekly KB digest\n\nshort body"

    assert split_telegram_message(text) == [text]


def test_send_split_sends_chunks_in_order(monkeypatch) -> None:
    text = "alpha\n\n" + ("x" * MAX_TELEGRAM_CHARS) + "\n\nomega"
    expected_chunks = split_telegram_message(text)
    sent = []

    def fake_send(**kwargs):
        sent.append(kwargs)

    monkeypatch.setattr("kb_feed.digest.send_telegram_message", fake_send)

    _send_split(bot_token="token", chat_id=111, text=text)

    assert [item["text"] for item in sent] == expected_chunks
    assert all(item["bot_token"] == "token" for item in sent)
    assert all(item["chat_id"] == 111 for item in sent)


def test_weekly_digest_writes_file_and_stores_dm_text(tmp_path) -> None:
    kb_root = _build_kb(tmp_path)
    store = _store(tmp_path)
    captured: dict = {}
    agent = FakeAgent(
        "Summary\n- Unfiltered links cluster around field gear.\n\nPossible new topics\n- field-geology-tools",
        captured=captured,
    )

    report = weekly_digest(
        store,
        kb_root,
        agent=agent,
        proposals_dir=tmp_path / "proposals",
        now=datetime(2026, 6, 1, 10, 0, tzinfo=timezone.utc),
    )

    assert report.ran is True
    assert report.item_count == 3
    assert report.proposals_path is not None
    body = report.proposals_path.read_text(encoding="utf-8")
    assert "field-geology-tools" in body
    assert "Generated by Claude CLI" in body
    assert "Weekly KB digest" in report.telegram_text
    assert store.get_meta(LAST_WEEKLY_DIGEST_TEXT_META_KEY) == report.telegram_text
    sent_prompt = json.loads(captured["prompt"])
    assert sent_prompt["allowed_existing_topics"] == ["obsidian", "rockhounding"]


