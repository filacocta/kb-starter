def test_claude_cli_digest_agent_sends_prompt_on_stdin(monkeypatch) -> None:
    captured: dict = {}

    class Completed:
        returncode = 0
        stdout = "digest response"
        stderr = ""

    def fake_run(args, **kwargs):
        captured["args"] = args
        captured["input"] = kwargs["input"]
        captured["cwd"] = kwargs["cwd"]
        captured["env"] = kwargs["env"]
        return Completed()

    monkeypatch.setattr("kb_feed.digest.subprocess.run", fake_run)

    agent = ClaudeCliDigestAgent(command=("claude", "-p", "--permission-mode", "plan"), timeout_seconds=10)

    assert agent.complete("private queue packet") == "digest response"
    assert captured["args"] == ["claude", "-p", "--permission-mode", "plan"]
    assert captured["input"] == "private queue packet"
    assert "private queue packet" not in captured["args"]
    assert "kb-feed-claude-" in captured["cwd"]
    assert "TELEGRAM_BOT_TOKEN" not in captured["env"]


